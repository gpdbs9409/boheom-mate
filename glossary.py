def lookup(question):
    """질문에 들어 있는 일상 표현에 해당하는 약관 용어 목록. 순서는 사전 순서를 따른다."""
    found = []
    for words, term in TERMS:
        if any(_contains(question, w) for w in words) and term not in found:
            found.append(term)
    return found


def _contains(question, word):
    # "암"처럼 한 글자 단어는 "암호", "암기" 같은 엉뚱한 단어에 걸리지 않게 뒤 글자를 확인한다.
    # ("위암이", "암으로", "암 진단"은 걸린다)
    if len(word) == 1:
        return re.search(rf"{word}($|[^가-힣]|[이을은에으])", question) is not None
    return word in question
